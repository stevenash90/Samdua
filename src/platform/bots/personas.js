// khớp nguyên từ (tránh "ăn" khớp nhầm vào "khăn", "căng"…)
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wordRe = ws => new RegExp('(^|[^\\p{L}])(' + ws.map(esc).join('|') + ')(?=$|[^\\p{L}])', 'iu');
const TOPIC_RE = Object.fromEntries(Object.entries(TOPIC_KEYS).map(([k, ws]) => [k, wordRe(ws)]));
function topicOf(text) {
  const s = String(text || '');
  for (const [tag, re] of Object.entries(TOPIC_RE)) if (re.test(s)) return tag;
  return null;
}
function mentions(persona, text) { return wordRe(persona.keys).test(String(text || '')); }

